def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Convert an RLinf actor DCP or DMuon checkpoint to DreamZero HF "
            "weights or an eval checkpoint directory."
        )
    )
    parser.add_argument(
        "--output-mode",
        required=True,
        choices=("weights", "eval"),
        help="Write only HF weights, or also package same-embodiment eval config.",
    )
    parser.add_argument(
        "--rlinf-checkpoint",
        required=True,
        help="Path to an RLinf global_step_* checkpoint directory.",
    )
    parser.add_argument(
        "--output-dir",
        required=True,
        help="Directory where the converted checkpoint will be written.",
    )
    parser.add_argument(
        "--rlinf-root",
        default=str(DEFAULT_RLINF_ROOT),
        help="Path to the RLinf repository containing the native converters.",
    )
    parser.add_argument(
        "--dreamzero-root",
        default=str(DEFAULT_DREAMZERO_ROOT),
        help="Path to the DreamZero-dev repository to add to PYTHONPATH.",
    )
    parser.add_argument(
        "--work-dir",
        default=None,
        help=(
            "Temporary work directory for the intermediate model.pt. Defaults to "
            "<output-dir>/_convert_work."
        ),
    )
    parser.add_argument(
        "--torch-dtype",
        default="bf16",
        help="Dtype passed to RLinf PT->HF converter. Use 'null' to preserve dtype.",
    )
    parser.add_argument(
        "--strict-load",
        default="true",
        choices=("true", "false"),
        help=(
            "Whether RLinf PT->HF conversion should require exact model keys. "
            "Default true checks the converted RLinf training checkpoint matches "
            "the instantiated DreamZero model exactly. 注意：这里校验的是 "
            "RLinf 训练 ckpt -> DreamZero 模型的加载；基础 Wan2.2 权重初始化 "
            "DreamZero 扩展模块时打印的 missing keys 不受这个参数影响。"
        ),
    )
    parser.add_argument(
        "--keep-pt",
        action="store_true",
        help="Keep the intermediate model.pt after conversion.",
    )
    parser.add_argument(
        "--skip-checkpoint-to-pt",
        action="store_true",
        help="Reuse an existing <work-dir>/model.pt and skip checkpoint merging.",
    )
    parser.add_argument(
        "--skip-pt-to-hf",
        action="store_true",
        help="Skip RLinf PT->HF conversion and only refresh existing output files.",
    )
    return parser.parse_args()


def run(cmd: list[str], *, cwd: Path, env: dict[str, str]) -> None:
    print("[CMD]", " ".join(cmd), flush=True)
    subprocess.run(cmd, cwd=str(cwd), env=env, check=True)


def resolve_paths(
    args: argparse.Namespace,
) -> tuple[str, Path, Path, Path, Path, Path, Path]:
    global_step_dir = Path(args.rlinf_checkpoint).resolve()
    actor_dir = global_step_dir / "actor"
    dcp_path = actor_dir / "dcp_checkpoint"
    dmuon_path = actor_dir / "dmuon_checkpoint"

    if dcp_path.is_dir():
        checkpoint_type = "dcp"
        checkpoint_path = dcp_path
    elif dmuon_path.is_dir():
        checkpoint_type = "dmuon"
        checkpoint_path = dmuon_path
    else:
        raise FileNotFoundError(
            f"No dcp_checkpoint or dmuon_checkpoint found under {actor_dir}"
        )

    run_dir = global_step_dir.parent.parent
    train_config = run_dir / "config.yaml"
    if not train_config.is_file():
        raise FileNotFoundError(f"RLinf train config not found: {train_config}")

    output_dir = Path(args.output_dir).resolve()
    source_exp_cfg = run_dir / "experiment_cfg"
    if args.output_mode == "eval":
        validate_eval_sources(train_config, source_exp_cfg)
    elif (output_dir / "experiment_cfg").exists():
        raise FileExistsError(
            "Weights output must not contain experiment_cfg; use a clean output "
            f"directory: {output_dir}"
        )

    work_dir = (
        Path(args.work_dir).resolve()
        if args.work_dir is not None
        else output_dir / "_convert_work"
    )
    return (
        checkpoint_type,
        checkpoint_path,
        global_step_dir,
        train_config,
        source_exp_cfg,
        output_dir,
        work_dir,
    )


def validate_eval_sources(train_config: Path, source_exp_cfg: Path) -> None:
    # 校验 eval 附件存在且与训练 embodiment 完全一致。
    conf_path = source_exp_cfg / "conf.yaml"
    metadata_path = source_exp_cfg / "metadata.json"
    if not conf_path.is_file():
        raise FileNotFoundError(f"RLinf DreamZero eval conf.yaml not found: {conf_path}")
    if not metadata_path.is_file():
        raise FileNotFoundError(f"RLinf DreamZero metadata.json not found: {metadata_path}")

    train_tag = str(OmegaConf.load(train_config).actor.model.embodiment_tag).strip()
    eval_tag = str(OmegaConf.load(conf_path).model.config.embodiment_tag).strip()
    if not train_tag or not eval_tag:
        raise ValueError("Train and eval embodiment_tag must not be empty.")
    if train_tag != eval_tag:
        raise ValueError(
            "Cross-embodiment eval packaging is not supported: "
            f"train={train_tag!r}, eval={eval_tag!r}."
        )

    with metadata_path.open("r", encoding="utf-8") as f:
        metadata = json.load(f)
    if not isinstance(metadata, dict) or eval_tag not in metadata:
        raise ValueError(
            f"Eval metadata must contain top-level tag {eval_tag!r}: {metadata_path}"
        )


def converter_env(args: argparse.Namespace) -> dict[str, str]:
    env = os.environ.copy()
    rlinf_root = str(Path(args.rlinf_root).resolve())
    dreamzero_root = str(Path(args.dreamzero_root).resolve())
    existing = env.get("PYTHONPATH", "")
    env["PYTHONPATH"] = os.pathsep.join(
        [p for p in (dreamzero_root, rlinf_root, existing) if p]
    )
    env.setdefault("REPO_PATH", rlinf_root)
    env.setdefault("DREAMZERO_PATH", dreamzero_root)
    env.setdefault("HF_HUB_OFFLINE", "1")
    env.setdefault("TOKENIZERS_PARALLELISM", "false")
    env.setdefault("HYDRA_FULL_ERROR", "1")
    return env


def convert_weights(
    args: argparse.Namespace,
    checkpoint_type: str,
    checkpoint_path: Path,
    train_config: Path,
    output_dir: Path,
    work_dir: Path,
) -> None:
    rlinf_root = Path(args.rlinf_root).resolve()
    work_dir.mkdir(parents=True, exist_ok=True)
    output_dir.mkdir(parents=True, exist_ok=True)

    model_pt = work_dir / "model.pt"
    env = converter_env(args)

    if args.skip_pt_to_hf:
        return

    if not args.skip_checkpoint_to_pt:
        if checkpoint_type == "dcp":
            merge_cmd = [
                sys.executable,
                "rlinf/utils/ckpt_convertor/fsdp_convertor/convert_dcp_to_pt.py",
                "--dcp_path",
                str(checkpoint_path),
                "--output_path",
                str(model_pt),
            ]
        elif checkpoint_type == "dmuon":
            merge_cmd = [
                sys.executable,
                "-m",
                "rlinf.utils.ckpt_convertor.fsdp_convertor.convert_dmuon_to_pt",
                "--checkpoint_path",
                str(checkpoint_path),
                "--output_path",
                str(model_pt),
            ]
        else:
            raise ValueError(f"Unsupported checkpoint type: {checkpoint_type!r}")
        run(merge_cmd, cwd=rlinf_root, env=env)
    elif not model_pt.is_file():
        raise FileNotFoundError(
            f"--skip-checkpoint-to-pt requested but missing: {model_pt}"
        )

    if not args.skip_pt_to_hf:
        run(
            [
                sys.executable,
                "-m",
                "rlinf.utils.ckpt_convertor.fsdp_convertor.convert_pt_to_hf",
                "--config-name",
                "fsdp_dreamzero_convertor",
                f"convertor.train_config_path={train_config}",
                f"convertor.ckpt_path={model_pt}",
                f"convertor.save_path={output_dir}",
                f"convertor.torch_dtype={args.torch_dtype}",
                f"convertor.strict_load={args.strict_load}",
                "convertor.export_experiment_cfg="
                f"{str(args.output_mode == 'eval').lower()}",
            ],
            cwd=rlinf_root,
            env=env,
        )

    if not args.keep_pt and model_pt.exists():
        model_pt.unlink()
        try:
            work_dir.rmdir()
        except OSError:
            pass


def normalize_config_json(output_dir: Path) -> dict:
    config_path = output_dir / "config.json"
    if not config_path.is_file():
        raise FileNotFoundError(f"Converted config.json not found: {config_path}")

    with config_path.open("r", encoding="utf-8") as f:
        config = json.load(f)

    # DreamZero-dev eval instantiates groot.vla.model.dreamzero.base_vla.VLA.
    # Keeping the architecture label native makes the converted checkpoint look
    # like the existing DreamZero checkpoints while preserving all extra fields.
    config["model_type"] = "vla"
    config["architectures"] = ["VLA"]
    config["model_dtype"] = "float32"

    action_head = config.get("action_head_cfg")
    if isinstance(action_head, dict):
        inner = action_head.get("config")
        if isinstance(inner, dict):
            inner["model_dtype"] = "float32"
            inner["skip_component_loading"] = True
            inner["defer_lora_injection"] = False

    with config_path.open("w", encoding="utf-8") as f:
        json.dump(config, f, ensure_ascii=False, indent=2)
        f.write("\n")
    return config


def complete_embodiment_tag_mappings(node) -> None:
    if isinstance(node, DictConfig):
        if "embodiment_tag_to_projector_index" in node:
            current = OmegaConf.to_container(
                node.embodiment_tag_to_projector_index, resolve=True
            ) or {}
            merged = {**DEFAULT_EMBODIMENT_TAG_MAPPING, **current}
            node.embodiment_tag_to_projector_index = OmegaConf.create(merged)

        if "embodiment_tag_mapping" in node:
            current = OmegaConf.to_container(
                node.embodiment_tag_mapping, resolve=True
            ) or {}
            merged = {**DEFAULT_EMBODIMENT_TAG_MAPPING, **current}
            node.embodiment_tag_mapping = OmegaConf.create(merged)

        for value in node.values():
            complete_embodiment_tag_mappings(value)
    elif isinstance(node, ListConfig):
        for value in node:
            complete_embodiment_tag_mappings(value)


def refresh_experiment_cfg(
    source_exp_cfg: Path,
    output_dir: Path,
    model_config: dict,
) -> None:
    output_exp = output_dir / "experiment_cfg"
    output_exp.mkdir(parents=True, exist_ok=True)

    conf = OmegaConf.load(source_exp_cfg / "conf.yaml")

    # Keep the RLinf-exported eval transforms, but update model.config to the
    # converted checkpoint's final config.json.
    conf.model._target_ = "groot.vla.model.dreamzero.base_vla.VLA"
    conf.model._convert_ = "object"
    conf.model.config = OmegaConf.create(model_config)
    conf.model.config._target_ = "groot.vla.model.dreamzero.base_vla.VLAConfig"
    conf.model.config._recursive_ = False

    conf.eval_bf16 = True
    conf.save_lora_only = False
    conf.relative_action = bool(model_config.get("relative_action", False))
    conf.relative_action_keys = list(model_config.get("relative_action_keys") or [])
    conf.relative_action_mode = model_config.get("relative_action_mode") or ""
    complete_embodiment_tag_mappings(conf)

    OmegaConf.save(conf, output_exp / "conf.yaml", resolve=True)
    shutil.copy2(source_exp_cfg / "metadata.json", output_exp / "metadata.json")


def validate_output(output_dir: Path, output_mode: str) -> None:
    # 按输出模式校验权重分片和 eval 附件。
    required = [
        output_dir / "config.json",
        output_dir / "model.safetensors.index.json",
    ]
    if not list(output_dir.glob("model-*.safetensors")):
        raise FileNotFoundError(
            f"Converted checkpoint has no safetensors shards: {output_dir}"
        )

    experiment_cfg = output_dir / "experiment_cfg"
    if output_mode == "weights":
        if experiment_cfg.exists():
            raise FileExistsError(
                f"Weights output unexpectedly contains experiment_cfg: {experiment_cfg}"
            )
    elif output_mode == "eval":
        required.extend(
            [experiment_cfg / "conf.yaml", experiment_cfg / "metadata.json"]
        )
    else:
        raise ValueError(f"Unsupported output mode: {output_mode!r}")

    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        raise FileNotFoundError(f"Converted checkpoint missing files: {missing}")


def main() -> None:
    args = parse_args()
    (
        checkpoint_type,
        checkpoint_path,
        _global_step_dir,
        train_config,
        source_exp_cfg,
        output_dir,
        work_dir,
    ) = resolve_paths(args)
    print(f"[INFO] checkpoint_type={checkpoint_type}")
    print(f"[INFO] checkpoint_path={checkpoint_path}")
    print(f"[INFO] train_config={train_config}")
    print(f"[INFO] source_exp_cfg={source_exp_cfg}")
    print(f"[INFO] output_dir={output_dir}")
    print(f"[INFO] work_dir={work_dir}")

    convert_weights(
        args,
        checkpoint_type,
        checkpoint_path,
        train_config,
        output_dir,
        work_dir,
    )
    model_config = normalize_config_json(output_dir)
    if args.output_mode == "eval":
        refresh_experiment_cfg(source_exp_cfg, output_dir, model_config)
    validate_output(output_dir, args.output_mode)

    print(f"[OK] DreamZero {args.output_mode} checkpoint ready:")
    print(output_dir)


if __name__ == "__main__":
    main()
